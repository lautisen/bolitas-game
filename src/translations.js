function getInitialLanguage() {
  const saved = localStorage.getItem('bolitasLang');
  if (saved && TRANSLATIONS[saved]) return saved;
  
  const navLang = navigator.language.split('-')[0];
  if (TRANSLATIONS[navLang]) return navLang;
  
  return 'en';
}

let currentLang = getInitialLanguage();

export function getLanguage() {
  return currentLang;
}

export function setLanguage(lang) {
  if (TRANSLATIONS[lang]) {
    currentLang = lang;
    localStorage.setItem('bolitasLang', lang);
    updateLanguageUI();
  }
}

export function t(key, params = {}) {
  let finalKey = key;
  // Standardize on parameter name for pluralization: val, target, or count
  const count = params.val !== undefined ? params.val : (params.target !== undefined ? params.target : params.count);
  
  if (count !== undefined && count > 1) {
    if (TRANSLATIONS[currentLang]?.[key + '_plural']) {
      finalKey = key + '_plural';
    }
  }
  
  let val = TRANSLATIONS[currentLang]?.[finalKey] || TRANSLATIONS['en']?.[finalKey] || finalKey;
  
  for (const [k, v] of Object.entries(params)) {
    val = val.split(`{{${k}}}`).join(v);
  }
  return val;
}

export function updateLanguageUI() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const params = el.getAttribute('data-i18n-params');
    const parsedParams = params ? JSON.parse(params) : {};
    
    if (el.tagName === 'INPUT' && el.type === 'text') {
      el.placeholder = t(key, parsedParams);
    } else {
      // If data-i18n-no-text is present, we only update attributes, not textContent
      const noText = el.hasAttribute('data-i18n-no-text');
      
      if (!noText) {
        // Keep only SVG/Icons if present, then replace text
        const icon = el.querySelector('svg, .icon, i');
        if (icon) {
          // Replace all text nodes with the translated text
          let found = false;
          el.childNodes.forEach(node => {
            if (node.nodeType === 3) {
              // Replace the first significant text node or clear others
              if (!found && node.textContent.trim() !== '') {
                node.textContent = ' ' + t(key, parsedParams);
                found = true;
              } else if (found) {
                node.textContent = '';
              }
            }
          });
          if (!found) {
            el.appendChild(document.createTextNode(' ' + t(key, parsedParams)));
          }
        } else {
          el.textContent = t(key, parsedParams);
        }
      }
    }

    // Always translate title if present
    if (el.hasAttribute('title')) {
      el.setAttribute('title', t(key, parsedParams));
    }
  });

  // Special cases like document title or other non-standard attributes
  document.title = "Gloop";
}
